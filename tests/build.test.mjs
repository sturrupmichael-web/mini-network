import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { build } from "../build.mjs";

const devHtml = await readFile(new URL("../dev.html", import.meta.url), "utf8");

export const tests = [
  ["build inlines everything into one file", async () => {
    const { html } = await build({ write: false });
    assert.match(html, /<!-- Generated by build\.mjs from dev\.html\. Do not edit/);
    assert.doesNotMatch(html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, ""), /\b(src|href)="/);
    assert.match(html, /<script type="module">/);
    assert.match(html, /<style>/);
  }],
  ["CSP hashes match the inline scripts", async () => {
    const { html } = await build({ write: false });
    const csp = html.match(/http-equiv="Content-Security-Policy" content="([^"]+)"/)[1];
    for (const part of [
      "default-src 'self'",
      "style-src 'self' 'unsafe-inline'",
      "img-src 'self' data: blob:",
      "connect-src 'self'",
      "object-src 'none'",
      "base-uri 'none'",
      "form-action 'none'",
    ]) {
      assert.ok(csp.includes(part), `CSP has ${part}`);
    }
    const scripts = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
    assert.ok(scripts.length >= 1);
    for (const code of scripts) {
      const hash = createHash("sha256").update(code, "utf8").digest("base64");
      assert.ok(csp.includes(`'sha256-${hash}'`), "script hash is in the CSP");
    }
    assert.equal((html.match(/Content-Security-Policy/g) ?? []).length, 1, "exactly one CSP");
  }],
  ["no absolute paths or other sites in the output", async () => {
    const { html } = await build({ write: false });
    assert.doesNotMatch(html, /\b(src|href)="\//);
    assert.doesNotMatch(html, /https?:\/\/(?!www\.w3\.org)/, "loads nothing from other sites");
  }],
  ["build fails if dev.html references a file that wasn't inlined", async () => {
    const broken = devHtml.replace("</body>", '<img src="images/logo.png" alt=""></body>');
    await assert.rejects(build({ source: broken, write: false }), /weren't inlined: images\/logo\.png/);
  }],
  ["build fails on a script from another site", async () => {
    const broken = devHtml.replace("</body>", '<script src="https://example.com/x.js"></script></body>');
    await assert.rejects(build({ source: broken, write: false }), /another site/);
  }],
];
