/**
 * Builds the single self-contained index.html from dev.html:
 *   - bundles and minifies src/main.js (and everything it imports from src/
 *     and data/) with esbuild, and inlines it as a module script
 *   - minifies and inlines every local stylesheet
 *   - replaces the CSP with one that allows exactly the inlined scripts
 *     (by sha256 hash)
 *   - fails if anything in dev.html still points at a local file
 *
 * Usage: node build.mjs   (or npm run build)
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const root = dirname(fileURLToPath(import.meta.url));
const OUT = join(root, "index.html");

const CSP = (scriptHashes) =>
  [
    "default-src 'self'",
    `script-src 'self' ${scriptHashes.map((h) => `'${h}'`).join(" ")}`.trim(),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join("; ");

/**
 * @param {object} [opts]
 * @param {string} [opts.source]  HTML to build instead of dev.html (tests use this).
 * @param {boolean} [opts.write]  Write index.html (default true).
 */
export async function build({ source, write = true } = {}) {
  let html = source ?? (await readFile(join(root, "dev.html"), "utf8"));

  // Scripts: <script type="module" src="..."></script>
  const scriptTags = [...html.matchAll(/<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>/g)];
  for (const [tag, src] of scriptTags) {
    if (isExternal(src)) throw new Error(`dev.html loads a script from another site: ${src}`);
    const result = await esbuild.build({
      entryPoints: [join(root, src)],
      bundle: true,
      minify: true,
      format: "esm",
      target: "es2022",
      write: false,
      legalComments: "none",
    });
    const code = result.outputFiles[0].text.trim();
    if (/<\/script/i.test(code)) throw new Error(`${src}: bundle contains "</script"; cannot inline safely`);
    html = html.replace(tag, () => `<script type="module">${code}</script>`);
  }

  // Stylesheets: <link rel="stylesheet" href="...">
  const linkTags = [...html.matchAll(/<link\b[^>]*\brel="stylesheet"[^>]*>/g)];
  for (const [tag] of linkTags) {
    const href = tag.match(/\bhref="([^"]+)"/)?.[1];
    if (!href || isExternal(href)) throw new Error(`dev.html has a stylesheet that can't be inlined: ${tag}`);
    const css = await readFile(join(root, href), "utf8");
    const min = await esbuild.transform(css, { loader: "css", minify: true, target: "es2022" });
    if (/<\/style/i.test(min.code)) throw new Error(`${href} contains "</style"`);
    html = html.replace(tag, () => `<style>${min.code.trim()}</style>`);
  }

  // Anything still pointing at a file means something wasn't inlined.
  const markup = html.replace(/(<(script|style)\b[^>]*>)[\s\S]*?(<\/\2>)/gi, "$1$3");
  const leftovers = [...markup.matchAll(/\b(?:src|href)="([^"]*)"/g)].map((m) => m[1]).filter((v) => !/^(#|data:|blob:)/.test(v));
  if (leftovers.length) {
    throw new Error(`dev.html still references files that weren't inlined: ${leftovers.join(", ")}`);
  }

  // CSP with a hash for every inline script.
  const hashes = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(
    (m) => `sha256-${createHash("sha256").update(m[1], "utf8").digest("base64")}`,
  );
  const cspTag = `<meta http-equiv="Content-Security-Policy" content="${CSP(hashes)}" />`;
  const cspPattern = /<meta\s+http-equiv="Content-Security-Policy"[^>]*>/i;
  html = cspPattern.test(html) ? html.replace(cspPattern, () => cspTag) : html.replace(/<head>/i, () => `<head>\n    ${cspTag}`);

  html = html.replace(
    /^<!doctype html>/i,
    "<!doctype html>\n<!-- Generated by build.mjs from dev.html. Do not edit: changes will be overwritten. -->",
  );

  if (write) await writeFile(OUT, html);
  return { html, out: OUT, bytes: Buffer.byteLength(html), hashes };
}

function isExternal(url) {
  return /^(?:[a-z]+:)?\/\//i.test(url);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const { bytes } = await build();
    console.log(`Built index.html (${(bytes / 1024).toFixed(1)} KB)`);
  } catch (e) {
    console.error(`Build failed: ${e.message}`);
    process.exit(1);
  }
}
